def render(cid: str, clip: Clip) -> str:
    if clip.role:
        anchor_block = f"画面中人物：{ANCHOR[clip.role]}。{KEEP[clip.role]}"
    else:
        lines = [f"{label}：{ANCHOR[r]}。" for label, r in GROUP_ROLES[cid]]
        lines.append("画面中所有人物的服装、发型、纹身、配饰、身形均保持与首帧完全一致。")
        anchor_block = "\n".join(lines)
    return "\n\n".join([
        f"【意图】{clip.intent}",
        f"【动作】{clip.action}",
        f"【镜头】{clip.camera}",
        f"【灯光】{clip.light}",
        anchor_block,
        f"【技术规格】{clip.spec}",
        NEGATIVES + clip.extra_neg,
    ]) + "\n"


